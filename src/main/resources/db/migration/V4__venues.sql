create table venues (
    id           bigint generated by default as identity primary key,
    organizer_id bigint       not null references users (id),
    name         varchar(100) not null,
    city         varchar(100) not null,
    address      varchar(255) not null,
    version      bigint       not null default 0,
    created_at   timestamptz  not null,
    updated_at   timestamptz  not null,
    created_by   bigint,
    updated_by   bigint
);

create index idx_venues_organizer_id on venues (organizer_id);

-- Deleting a venue lets the database delete its sections and seats (on delete cascade),
-- so we do not load thousands of rows only to remove them one by one.
create table sections (
    id         bigint generated by default as identity primary key,
    venue_id   bigint       not null references venues (id) on delete cascade,
    name       varchar(100) not null,
    sort_order int          not null,
    -- also serves as the index on venue_id
    constraint uk_sections_venue_name unique (venue_id, name)
);

create table seats (
    id          bigint generated by default as identity primary key,
    section_id  bigint      not null references sections (id) on delete cascade,
    row_label   varchar(20) not null,
    seat_number int         not null,
    -- also serves as the index on section_id
    constraint uk_seats_section_row_number unique (section_id, row_label, seat_number)
);
