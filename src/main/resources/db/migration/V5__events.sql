create table events (
    id           bigint generated by default as identity primary key,
    organizer_id bigint       not null references users (id),
    venue_id     bigint       not null references venues (id),
    title        varchar(200) not null,
    description  varchar(5000),
    category     varchar(20)  not null,
    starts_at    timestamptz  not null,
    status       varchar(20)  not null,
    version      bigint       not null default 0,
    created_at   timestamptz  not null,
    updated_at   timestamptz  not null,
    created_by   bigint,
    updated_by   bigint,
    constraint ck_events_category check (category in ('CONCERT', 'THEATRE', 'CONFERENCE', 'SPORT', 'OTHER')),
    constraint ck_events_status check (status in ('DRAFT', 'PUBLISHED', 'COMPLETED', 'CANCELLED'))
);

create index idx_events_organizer_id on events (organizer_id);
create index idx_events_venue_id on events (venue_id);
-- public search lists published events by date
create index idx_events_status_starts_at on events (status, starts_at);

create table price_categories (
    id         bigint generated by default as identity primary key,
    event_id   bigint         not null references events (id),
    section_id bigint         not null references sections (id),
    price      numeric(12, 2) not null,
    -- also serves as the index on event_id
    constraint uk_price_categories_event_section unique (event_id, section_id),
    constraint ck_price_categories_price check (price > 0)
);

create index idx_price_categories_section_id on price_categories (section_id);

-- One row per seat of the venue for each published event. This table is the single source of truth
-- for seat availability (see the concurrency rule); it is filled by one INSERT ... SELECT on publish.
create table event_seats (
    id                bigint generated by default as identity primary key,
    event_id          bigint      not null references events (id),
    seat_id           bigint      not null references seats (id),
    price_category_id bigint      not null references price_categories (id),
    status            varchar(20) not null,
    -- the foreign key to orders is added together with the orders table (booking step)
    order_id          bigint,
    hold_expires_at   timestamptz,
    version           bigint      not null default 0,
    -- also serves as the index on event_id
    constraint uk_event_seats_event_seat unique (event_id, seat_id),
    constraint ck_event_seats_status check (status in ('AVAILABLE', 'HELD', 'SOLD'))
);

create index idx_event_seats_event_status on event_seats (event_id, status);
create index idx_event_seats_seat_id on event_seats (seat_id);
create index idx_event_seats_price_category_id on event_seats (price_category_id);
