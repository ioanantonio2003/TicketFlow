create table orders (
    id              bigint generated by default as identity primary key,
    customer_id     bigint         not null references users (id),
    event_id        bigint         not null references events (id),
    status          varchar(20)    not null,
    -- set while the order is PENDING: the seats are released after this moment
    hold_expires_at timestamptz,
    total_amount    numeric(12, 2) not null default 0,
    version         bigint         not null default 0,
    created_at      timestamptz    not null,
    updated_at      timestamptz    not null,
    created_by      bigint,
    updated_by      bigint,
    constraint ck_orders_status check (status in ('PENDING', 'PAID', 'EXPIRED', 'CANCELLED', 'REFUNDED'))
);

-- also serves as the index on customer_id; used by "my orders" and the per-customer seat limit
create index idx_orders_customer_event on orders (customer_id, event_id);
create index idx_orders_event_id on orders (event_id);
-- used by the job that expires holds
create index idx_orders_status_hold_expires_at on orders (status, hold_expires_at);

create table order_items (
    id            bigint generated by default as identity primary key,
    order_id      bigint         not null references orders (id),
    event_seat_id bigint         not null references event_seats (id),
    -- price at the time of booking, copied from the price category
    price         numeric(12, 2) not null,
    constraint ck_order_items_price check (price > 0)
);

create index idx_order_items_order_id on order_items (order_id);
-- not unique: after an expiry or a refund the same seat can be booked again in another order
create index idx_order_items_event_seat_id on order_items (event_seat_id);

-- the foreign key that V5 left out until the orders table existed
alter table event_seats
    add constraint fk_event_seats_order foreign key (order_id) references orders (id);
create index idx_event_seats_order_id on event_seats (order_id);
