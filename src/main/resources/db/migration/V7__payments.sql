create table payments (
    id                  bigint generated by default as identity primary key,
    order_id            bigint         not null references orders (id),
    -- null until the provider has accepted the payment; unique so a webhook finds exactly one row
    provider_payment_id varchar(100) unique,
    status              varchar(20)    not null,
    amount              numeric(12, 2) not null,
    version             bigint         not null default 0,
    created_at          timestamptz    not null,
    updated_at          timestamptz    not null,
    created_by          bigint,
    updated_by          bigint,
    constraint ck_payments_status check (status in ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')),
    constraint ck_payments_amount check (amount > 0)
);

create index idx_payments_order_id on payments (order_id);

-- one row per (customer, Idempotency-Key); the primary key is what makes concurrent duplicates safe
create table idempotency_keys (
    key           varchar(100) not null,
    customer_id   bigint       not null references users (id),
    -- hash of what the request asked for; the same key with another request is rejected
    request_hash  varchar(64)  not null,
    -- null while the first request is still running
    status_code   integer,
    response_body text,
    created_at    timestamptz  not null,
    primary key (customer_id, key)
);
