create table tickets (
    id             bigint generated by default as identity primary key,
    order_id       bigint       not null references orders (id),
    event_id       bigint       not null references events (id),
    event_seat_id  bigint       not null references event_seats (id),
    customer_id    bigint       not null references users (id),
    -- 128 random bits, URL-safe Base64: this is what the QR code contains, so it must be unguessable
    code           varchar(64)  not null unique,
    status         varchar(20)  not null,
    used_at        timestamptz,
    -- a ticket is a snapshot: what was sold stays readable even if the event is edited later
    event_title    varchar(200) not null,
    section_name   varchar(100) not null,
    row_label      varchar(20)  not null,
    seat_number    integer      not null,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null,
    created_by     bigint,
    updated_by     bigint,
    constraint ck_tickets_status check (status in ('VALID', 'USED', 'CANCELLED'))
);

-- A seat has at most one live ticket. A cancelled ticket (refund, Step 12) does not block selling the seat again,
-- so the uniqueness covers only tickets that are not cancelled.
create unique index uq_tickets_live_event_seat on tickets (event_seat_id) where status <> 'CANCELLED';

create index idx_tickets_order_id on tickets (order_id);
create index idx_tickets_customer_id on tickets (customer_id);
create index idx_tickets_event_id on tickets (event_id);
